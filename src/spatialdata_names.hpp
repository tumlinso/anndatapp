inline bool valid_element_name(std::string_view name) {
    if (name.empty() || name == "." || name == ".." || name.starts_with("__")) return false;
    std::size_t offset = 0;
    while (offset < name.size()) {
        std::uint32_t cp;
        if (!name_detail::decode_one(name, offset, cp)) return false;
        if (cp == '-' || cp == '_' || cp == '.') continue;
        if (!name_detail::in_ranges(name_detail::kAlphanumeric, cp)) return false;
    }
    return true;
}

// Returns an empty key for malformed UTF-8. Callers validate names before use.
inline std::string lowercase_name(std::string_view name) {
    std::vector<std::uint32_t> codepoints;
    codepoints.reserve(name.size());
    std::size_t offset = 0;
    while (offset < name.size()) {
        std::uint32_t cp;
        if (!name_detail::decode_one(name, offset, cp)) return {};
        codepoints.push_back(cp);
    }
    std::vector<std::uint8_t> sigma_final(codepoints.size(), 0);
    bool previous_cased = false;
    for (std::size_t i = 0; i < codepoints.size(); ++i) {
        const std::uint32_t cp = codepoints[i];
        if (cp == 0x03A3u) sigma_final[i] = previous_cased;
        if (!name_detail::in_ranges(name_detail::kCaseIgnorable, cp))
            previous_cased = name_detail::in_ranges(name_detail::kCased, cp);
    }
    bool following_cased = false;
    for (std::size_t i = codepoints.size(); i > 0;) {
        const std::uint32_t cp = codepoints[--i];
        if (cp == 0x03A3u) sigma_final[i] = sigma_final[i] && !following_cased;
        if (!name_detail::in_ranges(name_detail::kCaseIgnorable, cp))
            following_cased = name_detail::in_ranges(name_detail::kCased, cp);
    }

    std::string result;
    result.reserve(name.size());
    for (std::size_t i = 0; i < codepoints.size(); ++i) {
        const std::uint32_t lowered = name_detail::lowercase_codepoint(
            codepoints[i], sigma_final[i] != 0, result);
        if (lowered != 0xFFFFFFFFu) name_detail::append_utf8(result, lowered);
    }
    return result;
}

