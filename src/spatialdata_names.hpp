template <std::size_t N>
inline bool in_ranges(const std::uint64_t (&ranges)[N], std::uint32_t cp) noexcept {
    constexpr std::uint64_t mask = (std::uint64_t{1} << 21) - 1;
    std::size_t first = 0, last = N;
    while (first < last) {
        const std::size_t middle = first + (last - first) / 2;
        const std::uint32_t range_first = static_cast<std::uint32_t>(ranges[middle] >> 21);
        const std::uint32_t range_last = static_cast<std::uint32_t>(ranges[middle] & mask);
        if (cp < range_first) last = middle;
        else if (cp > range_last) first = middle + 1;
        else return true;
    }
    return false;
}

inline bool decode_one(std::string_view text, std::size_t& offset, std::uint32_t& cp) noexcept {
    if (offset == text.size()) return false;
    const auto* bytes = reinterpret_cast<const unsigned char*>(text.data());
    const unsigned char first = bytes[offset++];
    if (first < 0x80) { cp = first; return true; }
    unsigned remaining;
    std::uint32_t minimum;
    if (first >= 0xC2 && first <= 0xDF) { remaining = 1; cp = first & 0x1Fu; minimum = 0x80; }
    else if (first >= 0xE0 && first <= 0xEF) { remaining = 2; cp = first & 0x0Fu; minimum = 0x800; }
    else if (first >= 0xF0 && first <= 0xF4) { remaining = 3; cp = first & 0x07u; minimum = 0x10000; }
    else return false;
    if (remaining > text.size() - offset) return false;
    for (unsigned i = 0; i < remaining; ++i) {
        const unsigned char next = bytes[offset++];
        if ((next & 0xC0u) != 0x80u) return false;
        cp = (cp << 6) | (next & 0x3Fu);
    }
    return cp >= minimum && cp <= 0x10FFFF && !(cp >= 0xD800 && cp <= 0xDFFF);
}

inline void append_utf8(std::string& out, std::uint32_t cp) {
    if (cp < 0x80) out.push_back(static_cast<char>(cp));
    else if (cp < 0x800) {
        out.push_back(static_cast<char>(0xC0u | (cp >> 6)));
        out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));
    } else if (cp < 0x10000) {
        out.push_back(static_cast<char>(0xE0u | (cp >> 12)));
        out.push_back(static_cast<char>(0x80u | ((cp >> 6) & 0x3Fu)));
        out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));
    } else {
        out.push_back(static_cast<char>(0xF0u | (cp >> 18)));
        out.push_back(static_cast<char>(0x80u | ((cp >> 12) & 0x3Fu)));
        out.push_back(static_cast<char>(0x80u | ((cp >> 6) & 0x3Fu)));
        out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));
    }
}

template <std::size_t N>
inline bool find_lower_point(const LowerPoint (&table)[N], std::uint32_t cp,
    std::uint32_t& target) noexcept {
    std::size_t first = 0, last = N;
    while (first < last) {
        const std::size_t middle = first + (last - first) / 2;
        if (cp < table[middle].source) last = middle;
        else if (cp > table[middle].source) first = middle + 1;
        else { target = table[middle].target; return true; }
    }
    return false;
}

inline std::uint32_t lowercase_codepoint(std::uint32_t cp, bool final_sigma,
    std::string& out) {
    if (cp == 0x03A3u && final_sigma) return 0x03C2u;
    for (const auto& mapping : kLowerExpansions) {
        if (mapping.source != cp) continue;
        const std::uint32_t values[] = {mapping.first, mapping.second, mapping.third};
        for (unsigned i = 0; i < mapping.size; ++i) append_utf8(out, values[i]);
        return 0xFFFFFFFFu;
    }
    std::size_t first = 0, last = sizeof(kLowerRanges) / sizeof(kLowerRanges[0]);
    while (first < last) {
        const std::size_t middle = first + (last - first) / 2;
        const auto& range = kLowerRanges[middle];
        if (cp < range.first) last = middle;
        else if (cp > range.last) first = middle + 1;
        else {
            if ((cp - range.first) % range.step == 0)
                return static_cast<std::uint32_t>(static_cast<std::int64_t>(cp) + range.delta);
            break;
        }
    }
    std::uint32_t target;
    return find_lower_point(kLowerPoints, cp, target) ? target : cp;
}

